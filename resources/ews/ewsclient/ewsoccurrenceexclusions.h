#pragma once

#include <QDateTime>
#include <QList>

#include <KCalendarCore/Calendar>
#include <KCalendarCore/Incidence>

#include "ewsid.h"

class EwsItem;

/**
  The moments a recurring item must stop generating: the slot of each of its
  cancelled occurrences.

  A moved occurrence is deliberately not one of them. Its own item carries the
  RECURRENCE-ID that is substituted at the slot generated by the rule of the
  master, so an exclusion on that slot would delete the only place where the
  occurrence can still be drawn.
 */
QList<QDateTime> ewsExclusionDateTimes(const EwsItem &item);

/**
  A moved occurrence of a recurring item: stored as an item of its own, so it has
  to be fetched separately and, unlike a cancelled one, not excluded anywhere.
 */
struct EwsMovedOccurrence {
    EwsId itemId;
    QDateTime originalStart;
};

/**
  The moved occurrences of a recurring item, as reported by its
  ModifiedOccurrences.
 */
QList<EwsMovedOccurrence> ewsMovedOccurrences(const EwsItem &item);

/**
  The incidence to store for a calendar item, and whether it is the master of its
  series.
 */
struct EwsCalendarIncidence {
    KCalendarCore::Incidence::Ptr incidence;
    bool isMaster = false;
};

/**
  Picks the incidence out of the calendar data of an item: the master of the series
  when the data hold one, otherwise the single event they hold.

  The server delivers a moved occurrence as an item of its own, and the calendar
  data of that item contain nothing but the occurrence with its RECURRENCE-ID. It is
  stored as it is - substituting it at the slot of the master is the work of the
  viewer.
 */
EwsCalendarIncidence ewsPickIncidence(const KCalendarCore::Calendar::Ptr &calendar);

/**
  Prepares the picked incidence for storage.

  The master of a series carries the exclusions of its cancelled occurrences. An
  occurrence delivered on its own keeps the RECURRENCE-ID the viewer substitutes at
  the slot of the master, but loses the rule of the series: a rule of its own would
  make it a second, endless series instead of one occurrence.
 */
void ewsPrepareForStorage(const EwsItem &item, EwsCalendarIncidence &picked);

/**
  Marks those moments as excluded from the recurrence of @p incidence, which does
  nothing when the incidence does not recur or its recurrence is read-only.
 */
void ewsApplyExclusions(KCalendarCore::Incidence &incidence, const QList<QDateTime> &exclusionDateTimes);
